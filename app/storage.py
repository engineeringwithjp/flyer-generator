def downscale_image(path: Path, max_edge: int, quality: int = 88) -> int:
    """Shrink an image in place. Returns bytes saved (0 if already small)."""
    try:
        with Image.open(path) as handle:
            image = handle.convert("RGB")
            width, height = image.size
    except Exception as exc:
        log.warning("Could not open %s: %s", path.name, exc)
        return 0

    if max(width, height) <= max_edge:
        return 0

    before = path.stat().st_size
    ratio = max_edge / max(width, height)
    resized = image.resize(
        (max(int(width * ratio), 1), max(int(height * ratio), 1)), Image.Resampling.LANCZOS
    )
    target = path.with_suffix(".jpg")
    resized.save(target, format="JPEG", quality=quality, optimize=True, progressive=True)
    if target != path:
        path.unlink(missing_ok=True)
    return max(before - target.stat().st_size, 0)


def downscale_library(
    max_edge: int | None = None,
    dry_run: bool = False,
    settings: Settings | None = None,
) -> StorageReport:
    """Bring every stored photo down to the largest size a flyer can use."""
    settings = settings or get_settings()
    max_edge = max_edge or settings.asset_max_edge
    report = StorageReport()

    roots = [settings.paths.clients, settings.paths.assets]
    for root in roots:
        if not root.exists():
            continue
        for path in sorted(root.rglob("*")):
            if path.suffix.lower() not in IMAGE_SUFFIXES or not path.is_file():
                continue
            if "logo" in path.parts or "fonts" in path.parts:
                continue  # logos are line art; fonts are not images
            if dry_run:
                try:
                    with Image.open(path) as image:
                        if max(image.size) > max_edge:
                            report.assets_downscaled += 1
                            report.freed_bytes += int(path.stat().st_size * 0.85)
                except Exception:
                    pass
                continue
            saved = downscale_image(path, max_edge)
            if saved:
                report.assets_downscaled += 1
                report.freed_bytes += saved

    if report.assets_downscaled:
        report.details.append(f"downscaled to {max_edge}px on the long edge")
    return report


# ------------------------------------------------------------------ overview


def usage(settings: Settings | None = None) -> dict[str, int]:
    """Bytes per area, for `flyer storage`."""
    settings = settings or get_settings()
    root = settings.paths.root
    clients = root / "clients"
    raw = sum(directory_size(p / "assets" / "raw") for p in clients.glob("*") if p.is_dir())
    approved = sum(
        directory_size(p / "assets" / "approved") for p in clients.glob("*") if p.is_dir()
    )
    areas = {
        "output (rendered flyers)": directory_size(settings.paths.output),
        "approved photography": approved,
        "unreviewed candidates": raw,
        "shared asset library": directory_size(settings.paths.assets),
        "git history": directory_size(root / ".git"),
        "python environment": directory_size(root / ".venv"),
        "claude worktrees": directory_size(root / ".claude" / "worktrees"),
    }
    return areas


def stale_worktrees(settings: Settings | None = None) -> list[tuple[Path, int]]:
    """Claude Code worktrees are scratch checkouts and duplicate the whole repo."""
    settings = settings or get_settings()
    base = settings.paths.root / ".claude" / "worktrees"
    if not base.exists():
        return []
    return [(p, directory_size(p)) for p in base.iterdir() if p.is_dir()]
